-- دليل حماة — المخطط الأساسي لقاعدة البيانات
-- القراءة العامة تتم فقط عبر دوال (RPC) آمنة، والجداول محمية بـ RLS.

create extension if not exists pgcrypto with schema extensions;

create schema if not exists private;
revoke all on schema private from public, anon, authenticated;

-- ───────────────────────── الجداول ─────────────────────────

create table public.categories (
  id        smallint generated by default as identity primary key,
  name      text not null unique check (char_length(name) between 2 and 60),
  icon      text not null default '📍',
  sort      smallint not null default 100,
  keywords  text not null default '',
  created_at timestamptz not null default now()
);

create table public.areas (
  id        smallint generated by default as identity primary key,
  name      text not null unique check (char_length(name) between 2 and 60),
  keywords  text not null default '',
  sort      smallint not null default 100
);

create type public.listing_status as enum ('pending', 'approved', 'hidden', 'rejected');

create table public.listings (
  id          bigint generated by default as identity primary key,
  name        text not null check (char_length(name) between 2 and 160),
  category_id smallint references public.categories(id) on delete set null,
  tags        text[] not null default '{}',
  phones      text[] not null default '{}',
  whatsapp    text,
  no_whatsapp boolean not null default false,
  area        text,
  address     text check (char_length(address) <= 400),
  map_url     text check (char_length(map_url) <= 1200),
  lat         double precision,
  lng         double precision,
  website     text check (char_length(website) <= 300),
  description text check (char_length(description) <= 600),
  featured    boolean not null default false,
  verified    boolean not null default false,
  status      public.listing_status not null default 'pending',
  source      text not null default 'admin',
  submitter_name  text,
  submitter_phone text,
  admin_note  text,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);
create index listings_status_updated_idx on public.listings (status, updated_at);
create index listings_category_idx on public.listings (category_id);
create index listings_phones_idx on public.listings using gin (phones);

create table public.reports (
  id          bigint generated by default as identity primary key,
  listing_id  bigint references public.listings(id) on delete set null,
  listing_name text,
  kind        text not null check (kind in ('wrong_number', 'wrong_info', 'closed', 'removal', 'abuse', 'other')),
  details     text check (char_length(details) <= 1000),
  contact     text check (char_length(contact) <= 60),
  status      text not null default 'open' check (status in ('open', 'resolved', 'dismissed')),
  created_at  timestamptz not null default now(),
  resolved_at timestamptz
);
create index reports_status_idx on public.reports (status, created_at desc);

create table public.settings (
  key        text primary key,
  value      jsonb not null,
  is_public  boolean not null default true,
  updated_at timestamptz not null default now()
);

create table public.admins (
  user_id    uuid primary key references auth.users(id) on delete cascade,
  email      text not null,
  role       text not null default 'editor' check (role in ('owner', 'editor')),
  created_at timestamptz not null default now()
);

create table public.listing_stats (
  listing_id bigint primary key references public.listings(id) on delete cascade,
  views    integer not null default 0,
  calls    integer not null default 0,
  whatsapp integer not null default 0,
  maps     integer not null default 0,
  shares   integer not null default 0,
  last_at  timestamptz not null default now()
);

create table public.daily_stats (
  day   date not null default current_date,
  kind  text not null,
  count integer not null default 0,
  primary key (day, kind)
);

create table public.search_terms (
  term    text primary key,
  hits    integer not null default 0,
  misses  integer not null default 0,
  last_at timestamptz not null default now()
);

create table public.audit_log (
  id         bigint generated by default as identity primary key,
  user_id    uuid,
  action     text not null,
  listing_id bigint,
  listing_name text,
  changes    jsonb,
  created_at timestamptz not null default now()
);
create index audit_log_created_idx on public.audit_log (created_at desc);

create table private.tombstones (
  listing_id bigint primary key,
  deleted_at timestamptz not null default now()
);

create table private.rate_hits (
  bucket text not null,
  at     timestamptz not null default now()
);
create index rate_hits_idx on private.rate_hits (bucket, at);

-- ───────────────────────── دوال مساعدة ─────────────────────────

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.admins where user_id = auth.uid());
$$;

create or replace function public.is_owner()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.admins where user_id = auth.uid() and role = 'owner');
$$;

create or replace function private.client_key()
returns text language sql stable set search_path = public as $$
  select encode(extensions.digest(coalesce(
    nullif(current_setting('request.headers', true)::json ->> 'cf-connecting-ip', ''),
    nullif(split_part(current_setting('request.headers', true)::json ->> 'x-forwarded-for', ',', 1), ''),
    'unknown') || ':dalil-hama', 'sha256'), 'hex');
$$;

-- يعيد true إذا كان العميل ضمن الحد المسموح، ويسجّل المحاولة
create or replace function private.allow(kind text, max_hits int, per interval)
returns boolean language plpgsql security definer set search_path = public as $$
declare
  b text := kind || ':' || private.client_key();
  n int;
begin
  if random() < 0.02 then
    delete from private.rate_hits where at < now() - interval '1 day';
  end if;
  select count(*) into n from private.rate_hits where bucket = b and at > now() - per;
  if n >= max_hits then
    return false;
  end if;
  insert into private.rate_hits (bucket) values (b);
  return true;
end $$;

-- توحيد صيغة الأرقام السورية: 09xxxxxxxx للجوال، وإزالة الرموز والبادئات الدولية
create or replace function public.normalize_phone(p text)
returns text language plpgsql immutable as $$
declare
  raw text;
  d text;
  intl boolean;
begin
  if p is null then return null; end if;
  raw := translate(p, '٠١٢٣٤٥٦٧٨٩۰۱۲۳۴۵۶۷۸۹', '01234567890123456789');
  intl := raw ~ '^\s*(\+|00)';
  d := regexp_replace(raw, '\D', '', 'g');
  if d = '' then return null; end if;
  if d like '00963%' then d := substr(d, 6);
  elsif d like '963%' and length(d) >= 11 then d := substr(d, 4);
  elsif intl and d !~ '^0*1' then return '+' || regexp_replace(d, '^00', '');
  end if;
  d := regexp_replace(d, '^0+', '');
  if length(d) >= 8 then return '0' || d; end if;
  return regexp_replace(raw, '\D', '', 'g');
end $$;

-- ───────────────────────── المشغّلات ─────────────────────────

create or replace function private.touch_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at := now();
  return new;
end $$;

create trigger listings_touch before update on public.listings
  for each row execute function private.touch_updated_at();

create or replace function private.listings_audit()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  diff jsonb := '{}'::jsonb;
  k text;
  o jsonb;
  n jsonb;
begin
  if tg_op = 'DELETE' then
    insert into private.tombstones (listing_id) values (old.id)
      on conflict (listing_id) do update set deleted_at = now();
    if auth.uid() is not null then
      insert into public.audit_log (user_id, action, listing_id, listing_name, changes)
      values (auth.uid(), 'delete', old.id, old.name, to_jsonb(old) - 'updated_at');
    end if;
    return old;
  end if;
  if auth.uid() is null then
    return new;
  end if;
  if tg_op = 'INSERT' then
    insert into public.audit_log (user_id, action, listing_id, listing_name, changes)
    values (auth.uid(), 'create', new.id, new.name, null);
    return new;
  end if;
  o := to_jsonb(old); n := to_jsonb(new);
  for k in select jsonb_object_keys(n) loop
    if k not in ('updated_at') and (o -> k) is distinct from (n -> k) then
      diff := diff || jsonb_build_object(k, jsonb_build_array(o -> k, n -> k));
    end if;
  end loop;
  if diff <> '{}'::jsonb then
    insert into public.audit_log (user_id, action, listing_id, listing_name, changes)
    values (auth.uid(), 'update', new.id, new.name, diff);
  end if;
  return new;
end $$;

create trigger listings_audit after insert or update or delete on public.listings
  for each row execute function private.listings_audit();

create or replace function private.settings_touch()
returns trigger language plpgsql as $$
begin
  new.updated_at := now();
  return new;
end $$;

create trigger settings_touch before update on public.settings
  for each row execute function private.settings_touch();

